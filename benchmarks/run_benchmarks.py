#!/usr/bin/env python3
"""
Automated benchmark runner for Native Kubernetes Service baseline.
Executes Smoke, Light, and Moderate profiles, capturing pre/post
Kubernetes resource usage, Prometheus metrics, and Locust performance.
"""

import os
import sys
import time
import json
import csv
import subprocess
import urllib.request
from datetime import datetime

RESULTS_DIR = os.path.join(os.path.dirname(__file__), "results")
os.makedirs(RESULTS_DIR, exist_ok=True)

PROFILES = [
    {
        "name": "smoke_test",
        "description": "Smoke Test (1 user, 10s)",
        "users": 1,
        "spawn_rate": 1,
        "duration": "10s",
        "duration_sec": 10
    },
    {
        "name": "light_load",
        "description": "Light Load (3 concurrent users, 30s)",
        "users": 3,
        "spawn_rate": 1,
        "duration": "30s",
        "duration_sec": 30
    },
    {
        "name": "moderate_load",
        "description": "Moderate Load (5 concurrent users, 30s)",
        "users": 5,
        "spawn_rate": 2,
        "duration": "30s",
        "duration_sec": 30
    }
]

def get_pod_resources():
    """Query current CPU and Memory for inference pods via kubectl top."""
    try:
        proc = subprocess.run(
            ["kubectl", "top", "pods", "-n", "mlops", "--no-headers"],
            capture_output=True,
            text=True,
            timeout=10
        )
        resources = {}
        for line in proc.stdout.strip().splitlines():
            parts = line.split()
            if len(parts) >= 3 and "inference-service" in parts[0]:
                pod_name = parts[0]
                cpu_raw = parts[1]
                mem_raw = parts[2]
                resources[pod_name] = {
                    "cpu": cpu_raw,
                    "memory": mem_raw
                }
        return resources
    except Exception as e:
        return {"error": str(e)}

def get_prometheus_counts():
    """Query Prometheus inference_requests_total across all replicas."""
    try:
        cmd = [
            "kubectl", "exec", "-n", "mlops", "deploy/prometheus", "--",
            "wget", "-qO-", "http://localhost:9090/api/v1/query?query=inference_requests_total"
        ]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=10)
        data = json.loads(proc.stdout)
        counts = {}
        for item in data.get("data", {}).get("result", []):
            rep = item["metric"].get("replica_id")
            status = item["metric"].get("status")
            val = int(float(item["value"][1]))
            if rep:
                if rep not in counts:
                    counts[rep] = {}
                counts[rep][status] = val
        return counts
    except Exception as e:
        return {"error": str(e)}

def parse_locust_stats(csv_prefix):
    """Parse output CSV files generated by Locust."""
    stats_file = f"{csv_prefix}_stats.csv"
    if not os.path.exists(stats_file):
        return {}

    summary = {}
    with open(stats_file, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("Name") == "Aggregated":
                req_count = int(row.get("Request Count", 0))
                fail_count = int(row.get("Failure Count", 0))
                rps = float(row.get("Requests/s", 0.0))
                avg_lat = float(row.get("Average Response Time", 0.0))
                min_lat = float(row.get("Min Response Time", 0.0))
                max_lat = float(row.get("Max Response Time", 0.0))
                med_lat = float(row.get("Median Response Time", 0.0))
                summary = {
                    "requests": req_count,
                    "failures": fail_count,
                    "failure_rate_pct": round((fail_count / max(1, req_count)) * 100.0, 2),
                    "throughput_rps": rps,
                    "client_avg_ms": avg_lat,
                    "client_min_ms": min_lat,
                    "client_max_ms": max_lat,
                    "client_p50_ms": med_lat
                }
                break

    # Also parse percentiles from stats CSV or stats_history if available
    pct_file = f"{csv_prefix}_stats.csv"
    if os.path.exists(pct_file):
        with open(pct_file, mode="r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if row.get("Name") == "Aggregated":
                    # Check percentiles columns
                    for col in ["50%", "95%", "99%"]:
                        if col in row and row[col]:
                            summary[f"client_p{col.replace('%', '')}_ms"] = float(row[col])

    return summary

def run_profile(profile, host="http://localhost:8000"):
    print("\n" + "=" * 70)
    print(f"RUNNING PROFILE: {profile['description']}")
    print(f"Target: {host} | Concurrency: {profile['users']} | Duration: {profile['duration']}")
    print("=" * 70)

    # 1. Pre-test state capture
    pre_resources = get_pod_resources()
    pre_prom_counts = get_prometheus_counts()
    print("Pre-test Pod Resources:", pre_resources)

    # 2. Run Locust
    csv_prefix = os.path.join(RESULTS_DIR, profile["name"])
    locustfile_path = os.path.join(os.path.dirname(__file__), "locustfile.py")
    cmd = [
        sys.executable, "-m", "locust",
        "-f", locustfile_path,
        "--headless",
        "-u", str(profile["users"]),
        "-r", str(profile["spawn_rate"]),
        "-t", profile["duration"],
        "--host", host,
        "--csv", csv_prefix
    ]

    t0 = time.time()
    proc = subprocess.run(cmd, capture_output=True, text=True)
    duration_actual = time.time() - t0

    # Print Locust stdout for transparency
    print(proc.stdout)
    if proc.stderr:
        print("Locust stderr:", proc.stderr)

    # 3. Post-test state capture
    time.sleep(1) # wait briefly for Metrics Server / Prometheus scrape
    post_resources = get_pod_resources()
    post_prom_counts = get_prometheus_counts()

    # 4. Parse results
    locust_summary = parse_locust_stats(csv_prefix)

    # Calculate replica traffic distribution delta from Prometheus
    replica_delta = {}
    if isinstance(pre_prom_counts, dict) and isinstance(post_prom_counts, dict):
        for rep, stats in post_prom_counts.items():
            post_200 = stats.get("200", 0)
            pre_200 = pre_prom_counts.get(rep, {}).get("200", 0)
            replica_delta[rep] = max(0, post_200 - pre_200)

    total_delta = sum(replica_delta.values())
    traffic_distribution_pct = {}
    if total_delta > 0:
        for rep, count in replica_delta.items():
            traffic_distribution_pct[rep] = round((count / total_delta) * 100.0, 1)

    result_entry = {
        "profile": profile["name"],
        "description": profile["description"],
        "timestamp_utc": datetime.utcnow().isoformat() + "Z",
        "concurrency_users": profile["users"],
        "spawn_rate": profile["spawn_rate"],
        "duration_configured": profile["duration"],
        "duration_actual_sec": round(duration_actual, 2),
        "locust_metrics": locust_summary,
        "prometheus_replica_delta": replica_delta,
        "traffic_distribution_pct": traffic_distribution_pct,
        "pod_resources_before": pre_resources,
        "pod_resources_after": post_resources
    }

    return result_entry

def main():
    target_host = os.environ.get("TARGET_HOST", "http://localhost:8000")
    print(f"Initiating Benchmark Harness for Target Host: {target_host}")

    # Initial Connectivity Check
    try:
        with urllib.request.urlopen(f"{target_host}/health", timeout=3.0) as resp:
            data = json.loads(resp.read().decode())
            print(f"Initial Health Check PASSED: {data}")
    except Exception as e:
        print(f"FATAL: Target host {target_host}/health unreachable: {e}")
        sys.exit(1)

    all_results = []
    for p in PROFILES:
        res = run_profile(p, host=target_host)
        all_results.append(res)
        time.sleep(3) # Cool-down between profiles

    # Save comprehensive machine-readable summary
    summary_path = os.path.join(RESULTS_DIR, "baseline_summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(all_results, f, indent=2)

    print("\n" + "=" * 70)
    print(f"ALL BENCHMARKS COMPLETED. Summary saved to: {summary_path}")
    print("=" * 70)

if __name__ == "__main__":
    main()
